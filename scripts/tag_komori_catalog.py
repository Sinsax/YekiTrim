def main() -> None:
    cat = json.load(open("experiments/komori_full_catalog.json", encoding="utf-8"))
    for e in cat:
        e["tags"] = SUBCAT_TAGS.get((e["page"], e["subcat"]),
                                    PAGE_FALLBACK.get(e["page"], []))
    out = "experiments/komori_tagged_catalog.json"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(cat, f, ensure_ascii=False, indent=1)

    # 统计
    tag_count: Counter[str] = Counter()
    untagged = 0
    for e in cat:
        if e["tags"]:
            for t in e["tags"]:
                tag_count[t] += 1
        else:
            untagged += 1
    print(f"总条目: {len(cat)}, 未标记: {untagged}")
    print("tag 分布:")
    for t, n in sorted(tag_count.items(), key=lambda x: -x[1]):
        print(f"  {t:12s} {n:4d}")
    print(f"catalog 已保存: {out}")


if __name__ == "__main__":
    main()
